#!/usr/bin/env python3
"""Regenerate audioManifest.ts — only slides that have a teacher recording."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app", "src", "data", "teacherLessons", "audioManifest.ts")
REPORT = "/tmp/audio_map_report.json"

data = {1: [12, 15, 27, 36, 1011]}
if os.path.exists(REPORT):
    rep = json.load(open(REPORT))
    for k, items in rep.items():
        n = int(k[1:])
        nums = sorted(x["num"] for x in items if x["status"] == "ok")
        if nums:
            data[n] = nums

body = ",\n".join(f"  {k}: [{', '.join(map(str, v))}]" for k, v in sorted(data.items()))
src = f"""/* generated by scripts/gen_audio_manifest.py */
export const AUDIO_SCENES: Record<number, number[]> = {{
{body},
}}
"""
open(OUT, "w").write(src)
print("wrote", OUT, {k: len(v) for k, v in data.items()})
